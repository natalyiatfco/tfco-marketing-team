import { Router, type IRouter } from "express";
import { and, desc, eq, isNotNull } from "drizzle-orm";
import PDFDocument from "pdfkit";
import { db, tasksTable, agentsTable, propertiesTable } from "@workspace/db";

const router: IRouter = Router();

router.get("/reports", async (req, res): Promise<void> => {
  const propertyId = req.query.propertyId ? Number(req.query.propertyId) : undefined;

  const conditions = [isNotNull(tasksTable.output)];
  if (propertyId) {
    conditions.push(eq(tasksTable.propertyId, propertyId));
  }

  const reports = await db
    .select({
      id: tasksTable.id,
      title: tasksTable.title,
      output: tasksTable.output,
      createdAt: tasksTable.createdAt,
      agentId: tasksTable.agentId,
      propertyId: tasksTable.propertyId,
      agentName: agentsTable.name,
      agentIcon: agentsTable.icon,
      agentColor: agentsTable.color,
      propertyName: propertiesTable.name,
    })
    .from(tasksTable)
    .innerJoin(agentsTable, eq(tasksTable.agentId, agentsTable.id))
    .innerJoin(propertiesTable, eq(tasksTable.propertyId, propertiesTable.id))
    .where(and(...conditions))
    .orderBy(desc(tasksTable.createdAt))
    .limit(100);

  res.json(reports.map((r) => ({
    id: r.id,
    title: r.title,
    agentId: r.agentId,
    agentName: r.agentName,
    agentIcon: r.agentIcon,
    agentColor: r.agentColor,
    propertyId: r.propertyId,
    propertyName: r.propertyName,
    outputSnippet: r.output ? r.output.substring(0, 200) : null,
    createdAt: r.createdAt?.toISOString() ?? null,
  })));
});

